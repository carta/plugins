// Places a formula spec's templates in a workbook, styles them, and checks them.
// Pure functions, plus `writePage` and `verify`, which take an Office context, and `applyStyles`, which takes worksheets.
// `pages` are the formula spec command's complete pages 1..pages, in order.

// A check matches within a cent for amounts, and within half of the 0.01% a share shows.
const TOLERANCE = 0.01;
const PERCENT_TOLERANCE = 0.00005;
const FILL = '#FCF9F4';
const FONT = 'Arial';
const SOURCE_LINE = 'Source: Carta — Waterfall Modeling';

// A name in a template: {block.col}, {block[row].col}; a tool result can carry a row-less name's dot as `[.]`.
const TOKEN = /\{([a-z0-9_]+)(?:\[([^\]]+)])?(?:\.|\[\.\])([a-z0-9_]+)\}/g;
const NAME = /^(.*)\[(.*)\]\.(.*)$/;
// Excel's limit on a sheet name's length.
const SHEET_NAME_MAX = 31;

// A literal string as Excel stores it through range.formulas: one that Excel would parse as a formula
// (a leading =, +, - or @) is kept as text by a leading apostrophe. Only a spec template becomes a formula.
function asText(value) {
  return typeof value === 'string' && /^[=+\-@]/.test(value) ? "'" + value : value;
}

function colName(index) {
  let name = '';
  for (let n = index + 1; n > 0; n = Math.floor((n - 1) / 26)) name = String.fromCharCode(65 + ((n - 1) % 26)) + name;
  return name;
}

// The A1 address of a 0-based row and column; `absolute` adds the `$` signs.
function a1(row, col, absolute = false) {
  const $ = absolute ? '$' : '';
  return $ + colName(col) + $ + (row + 1);
}

// The 0-based {row, col} of a one-cell A1 address such as 'C12'.
function parseA1(address) {
  const m = /^\$?([A-Z]+)\$?([0-9]+)$/.exec(address);
  return { row: Number(m[2]) - 1, col: [...m[1]].reduce((n, ch) => n * 26 + ch.charCodeAt(0) - 64, 0) - 1 };
}

// A confirmed client cell from its A1 address: 'Model!C5', or a holder range in one column,
// "'Deal Model'!D10:D41" → {sheet, row, col, lastRow}.
function boundCell(address) {
  const { sheet, cells } = partsOf(address);
  const [first, last, extra] = cells.split(':');
  if (sheet === null || !first || extra !== undefined) throw new Error('Not a sheet-qualified address: ' + address);
  const start = parseA1(first);
  const cell = { sheet, row: start.row, col: start.col };
  if (last === undefined) return cell;
  const end = parseA1(last);
  if (end.col !== start.col) throw new Error('A holder range spans one column: ' + address);
  return { ...cell, lastRow: end.row };
}

function keyOf(block, row, col) {
  return block + '[' + row + '].' + col;
}

function tabKey(sheet) {
  return 'CartaTab__' + sheet.replace(/[^A-Za-z0-9_]/g, '_');
}

function sheetPrefix(sheet, onSheet) {
  if (sheet === onSheet) return '';
  const plain = /^[A-Za-z_][A-Za-z0-9_.]*$/.test(sheet) && !/^[A-Za-z]{1,3}[0-9]+$/.test(sheet) && !/^(TRUE|FALSE)$/i.test(sheet);
  return (plain ? sheet : "'" + sheet.replace(/'/g, "''") + "'") + '!';
}

// Every block's description, in order: a page carries the descriptions of the blocks that start on it.
function blocksOf(pages) {
  return pages.flatMap((page) => page.blocks || []);
}

function blockRows(pages) {
  const rows = {};
  for (const block of blocksOf(pages)) rows[block.key] = [];
  for (const page of pages) {
    for (const run of page.rows || []) {
      if (!rows[run.block]) throw new Error('No block ' + run.block);
      run.rows.forEach((row, i) => { rows[run.block][run.first_row + i] = row; });
    }
  }
  return rows;
}

function holderCount(pages) {
  const rows = blockRows(pages);
  return blocksOf(pages).filter((b) => b.repeats).reduce((n, b) => n + rows[b.key].filter((r) => r.set !== undefined).length, 0);
}

// opts.sheet: put every block on this sheet (adapt mode's 'Carta inputs').
// opts.sheets: write a sheet under another name, {"Cap Table": "Cap Table (Carta)"}; it renames opts.sheet too.
// opts.cells: confirmed client cells by A1 address, {"block[row].col": "Model!C5", "block[*].col": "Model!D10:D41"}.
// opts.figuresOnly: leave out the repeating blocks.
// opts.now: the report's generated time, a Date; the current time by default.
// A sheet of several blocks opens with the report header (rows 1-3) and titles each block;
// a sheet's only block has neither. A block whose headings are all empty has no heading row.
function layout(pages, opts = {}) {
  const rows = blockRows(pages);
  const generated = 'Generated by Carta at ' + (opts.now || new Date()).toISOString().slice(0, 16).replace('T', ' ') + ' UTC';
  const binding = { sheets: [], specs: {}, headers: [], blocks: {}, cells: Object.fromEntries(Object.entries(opts.cells || {}).map(([name, address]) => [name, boundCell(address)])) };
  const placed = [];
  const count = {};
  for (const block of blocksOf(pages)) {
    if (opts.figuresOnly && block.repeats) {
      binding.blocks[block.key] = { skipped: true };
      continue;
    }
    const target = opts.sheet || block.sheet;
    const sheet = (opts.sheets && opts.sheets[target]) || target;
    placed.push({ block, sheet });
    count[sheet] = (count[sheet] || 0) + 1;
  }
  const next = {};
  for (const { block, sheet } of placed) {
    if (!(sheet in next)) {
      binding.sheets.push(sheet);
      binding.specs[sheet] = opts.sheet || block.sheet;
      const header = count[sheet] > 1 && !opts.sheet;
      if (header) binding.headers.push({ sheet, title: 'Waterfall Report - Entity: ' + pages[0].entity, line: generated });
      next[sheet] = header ? 3 : 0;
    }
    let at = next[sheet];
    const title = count[sheet] > 1 ? at++ : null;
    const heading = block.columns.some((c) => c.heading) ? at++ : null;
    const cols = {};
    block.columns.forEach((c, i) => { cols[c.key] = i; });
    const keyed = {};
    let first = null;
    let last = null;
    rows[block.key].forEach((row, i) => {
      keyed[row.key] = at + i;
      if (row.set !== undefined) { first = first === null ? at + i : first; last = at + i; }
    });
    binding.blocks[block.key] = { sheet, title, heading, cols, rows: keyed, holders: first === null ? null : [first, last] };
    next[sheet] = at + rows[block.key].length + 1;
  }
  // A [*] range reads its holder rows where the block puts them, so a holder row maps only as a whole column.
  const repeating = new Set(blocksOf(pages).filter((b) => b.repeats).map((b) => b.key));
  for (const name of Object.keys(binding.cells)) {
    const [, block, row, col] = NAME.exec(name) || [];
    if (repeating.has(block) && rows[block].some((r) => r.key === row && r.set !== undefined)) {
      throw new Error('Holder row ' + name + ' maps only as ' + block + '[*].' + col);
    }
  }
  // A holder column mapped to a client range holds Carta's holder rows there, one per row of the range.
  for (const block of blocksOf(pages)) {
    if (!block.repeats || binding.blocks[block.key].skipped) continue;
    const holders = rows[block.key].filter((r) => r.set !== undefined);
    for (const column of block.columns) {
      const name = keyOf(block.key, '*', column.key);
      const range = binding.cells[name];
      if (!range) continue;
      const height = (range.lastRow === undefined ? range.row : range.lastRow) - range.row + 1;
      if (height !== holders.length) {
        throw new Error('Holder range ' + name + ' has ' + height + ' rows; the block has ' + holders.length + ' holder rows');
      }
      holders.forEach((r, i) => {
        binding.cells[keyOf(block.key, r.key, column.key)] = { sheet: range.sheet, row: range.row + i, col: range.col };
      });
    }
  }
  return binding;
}

function resolve(binding, blockKey, rowKey, colKey, onSheet) {
  const bound = binding.cells[keyOf(blockKey, rowKey, colKey)];
  if (bound) {
    const end = bound.lastRow === undefined ? '' : ':' + a1(bound.lastRow, bound.col, true);
    return sheetPrefix(bound.sheet, onSheet) + a1(bound.row, bound.col, true) + end;
  }
  const block = binding.blocks[blockKey];
  if (!block) throw new Error('No block ' + blockKey);
  if (block.skipped) throw new Error('Block ' + blockKey + ' is not written');
  const col = block.cols[colKey];
  if (col === undefined) throw new Error('Block ' + blockKey + ' has no column ' + colKey);
  const prefix = sheetPrefix(block.sheet, onSheet);
  if (rowKey === '*') {
    if (!block.holders) throw new Error('Block ' + blockKey + ' has no holder rows');
    return prefix + a1(block.holders[0], col, true) + ':' + a1(block.holders[1], col, true);
  }
  if (rowKey === 'heading' && block.heading === null) throw new Error('Block ' + blockKey + ' has no heading row');
  const row = rowKey === 'heading' ? block.heading : block.rows[rowKey];
  if (row === undefined) throw new Error('Block ' + blockKey + ' has no row ' + rowKey);
  return prefix + a1(row, col, true);
}

// Where a written cell goes: its confirmed client cell, else its place in the block.
function locate(binding, blockKey, rowKey, colKey) {
  const bound = binding.cells[keyOf(blockKey, rowKey, colKey)];
  if (bound) return { sheet: bound.sheet, row: bound.row, col: bound.col, bound: true };
  const b = binding.blocks[blockKey];
  return { sheet: b.sheet, row: b.rows[rowKey], col: b.cols[colKey], bound: false };
}

// The template as an A1 formula written on `sheet`; a row-less name reads row `rowKey`.
function render(template, sheet, rowKey, binding) {
  return '=' + template.replace(TOKEN, (_, block, row, col) => resolve(binding, block, row === undefined ? rowKey : row, col, sheet));
}

function readsSkipped(template, binding) {
  return [...template.matchAll(TOKEN)].some((m) => binding.blocks[m[1]] && binding.blocks[m[1]].skipped);
}

// The spec's checked value as a number, or null when it has none.
function checkOf(cell) {
  const n = cell.check === undefined || cell.check === null ? NaN : Number(cell.check);
  return Number.isFinite(n) ? n : null;
}

function cellOf(block, row, i) {
  const cell = row.cells[i];
  if (cell !== null && cell !== undefined) return typeof cell === 'object' ? cell : { value: cell };
  const f = row.set === undefined ? undefined : block.templateSets[row.set][block.columns[i].key];
  return f === undefined ? null : { f };
}

function blocksByKey(pages) {
  const byKey = {};
  for (const block of blocksOf(pages)) byKey[block.key] = block;
  return byKey;
}

function eachCell(pages, page, fn) {
  const byKey = blocksByKey(pages);
  for (const run of page.rows || []) {
    const block = byKey[run.block];
    run.rows.forEach((row) => block.columns.forEach((c, i) => fn(block, row, c.key, cellOf(block, row, i))));
  }
}

// The writes for one page: [{sheet, address, formulas}] for range.formulas; null leaves a cell as is.
function cellsToWrite(binding, pages, pageNumber) {
  const page = pages[pageNumber - 1];
  const grids = {};
  const writes = [];
  const gridFor = (key) => {
    if (!grids[key]) grids[key] = { sheet: binding.blocks[key].sheet, rows: {} };
    return grids[key];
  };
  if (pageNumber === 1) {
    for (const h of binding.headers) writes.push({ sheet: h.sheet, address: 'A1:A2', formulas: [[asText(h.title)], [asText(h.line)]] });
  }
  for (const block of page.blocks || []) {
    const b = binding.blocks[block.key];
    if (b.skipped) continue;
    const width = block.columns.length;
    if (b.title !== null) gridFor(block.key).rows[b.title] = [asText(block.title)].concat(new Array(width - 1).fill(null));
    if (b.heading !== null) gridFor(block.key).rows[b.heading] = block.columns.map((c) => asText(c.heading));
  }
  eachCell(pages, page, (block, row, colKey, cell) => {
    const b = binding.blocks[block.key];
    if (b.skipped) return;
    const grid = gridFor(block.key);
    const at = b.rows[row.key];
    if (!grid.rows[at]) grid.rows[at] = new Array(block.columns.length).fill(null);
    if (!cell) return;
    const place = locate(binding, block.key, row.key, colKey);
    let written = asText(cell.value);
    if (cell.f !== undefined) {
      written = readsSkipped(cell.f, binding) ? checkOf(cell) : render(cell.f, place.sheet, row.key, binding);
    }
    if (place.bound) writes.push({ sheet: place.sheet, address: a1(place.row, place.col), formulas: [[written]] });
    else grid.rows[place.row][place.col] = written;
  });
  for (const key of Object.keys(grids)) {
    const grid = grids[key];
    const at = Object.keys(grid.rows).map(Number).sort((x, y) => x - y);
    let start = 0;
    for (let i = 1; i <= at.length; i++) {
      if (i < at.length && at[i] === at[i - 1] + 1) continue;
      const rows = at.slice(start, i).map((r) => grid.rows[r]);
      writes.push({ sheet: grid.sheet, address: a1(at[start], 0) + ':' + a1(at[i - 1], rows[0].length - 1), formulas: rows });
      start = i;
    }
  }
  return writes;
}

// Every written formula the spec checks, leaving out those written as their checked value: [{name, sheet, address, check}].
function checks(binding, pages) {
  const out = [];
  pages.forEach((page) => eachCell(pages, page, (block, row, colKey, cell) => {
    if (binding.blocks[block.key].skipped || !cell || cell.f === undefined || readsSkipped(cell.f, binding)) return;
    const check = checkOf(cell);
    if (check === null) return;
    const place = locate(binding, block.key, row.key, colKey);
    out.push({ name: keyOf(block.key, row.key, colKey), label: row.label, heading: block.columns.find((c) => c.key === colKey).heading,
      sheet: place.sheet, address: a1(place.row, place.col), check });
  }));
  return out;
}

function toleranceOf(name) {
  const [, blockKey, rowKey, colKey] = NAME.exec(name);
  return formatOf(blockKey, rowKey, colKey) === '0.00%' ? PERCENT_TOLERANCE : TOLERANCE;
}

// `values[i]` is the workbook's value at `list[i]`.
function compare(list, values) {
  const rows = list.map((c, i) => ({ ...c, actual: values[i],
    status: typeof values[i] === 'number' && Math.abs(values[i] - c.check) <= toleranceOf(c.name) ? 'Match' : 'Mismatch' }));
  const mismatches = rows.filter((r) => r.status === 'Mismatch');
  return { checked: rows.length, matched: rows.length - mismatches.length, mismatches, rows };
}

// The spec name of the cell at `address` (e.g. 'C12') on `sheet`, or null: only cells the renderer writes, a bound cell at its client cell.
function nameAt(binding, sheet, address) {
  const at = parseA1(address);
  for (const [name, c] of Object.entries(binding.cells)) {
    if (c.lastRow === undefined && c.sheet === sheet && c.row === at.row && c.col === at.col) return name;
  }
  for (const [key, b] of Object.entries(binding.blocks)) {
    if (b.skipped || b.sheet !== sheet) continue;
    const row = Object.keys(b.rows).find((k) => b.rows[k] === at.row);
    const col = Object.keys(b.cols).find((k) => b.cols[k] === at.col);
    if (row !== undefined && col !== undefined && !binding.cells[keyOf(key, row, col)]) return keyOf(key, row, col);
  }
  return null;
}

// The cell at `address` on `sheet` in words, or null when it isn't one of Carta's:
// {name, block, explains, row, heading, formula}; `formula` names each input [block · row · heading], null for an input.
function explain(binding, pages, sheet, address) {
  const name = nameAt(binding, sheet, address);
  if (name === null) return null;
  const [, blockKey, rowKey, colKey] = NAME.exec(name);
  const byKey = blocksByKey(pages);
  const rows = blockRows(pages);
  const words = (b, r, c) => {
    const block = byKey[b];
    const row = r === '*' ? 'every holder row' : r === 'heading' ? 'heading' : rows[b].find((x) => x.key === r).label;
    const column = block.columns.find((x) => x.key === c);
    return '[' + block.title + ' · ' + row + ' · ' + (column.heading || c) + ']';
  };
  const block = byKey[blockKey];
  const row = rows[blockKey].find((r) => r.key === rowKey);
  const i = block.columns.findIndex((c) => c.key === colKey);
  const cell = cellOf(block, row, i);
  const formula = cell && cell.f !== undefined
    ? cell.f.replace(TOKEN, (_, b, r, c) => words(b, r === undefined ? rowKey : r, c)) : null;
  return { name, block: block.title, explains: block.explains, row: row.label, heading: block.columns[i].heading, formula };
}

// Each cell's number format, by its block, row and column key: the first rule that names it wins,
// and anything left is currency.
const NUMBER_FORMATS = [
  { format: 'General', columns: ['label', 'breakpoint', 'holder_name', 'interest_type', 'class', 'interest', 'holder_id', 'interest_id', 'holder'] },
  { format: 'yyyy-mm-dd', rows: { scenario: ['valuation_date'] } },
  { format: '#,##0.00', columns: ['quantity', 'participating_quantity'], rows: { class_summary: ['participating_quantity'] } },
  { format: '0.00%', columns: ['of_proceeds'] },
];

function currencySymbol(currency) {
  return new Intl.NumberFormat('en', { style: 'currency', currency }).formatToParts(0).find((p) => p.type === 'currency').value;
}

// The results' currency; absent → USD (SKILL.md §Step 3).
function currencyOf(currency) {
  return currency || 'USD';
}

// The accounting format of excel-output.md §Write mechanics in the results' currency.
function currencyFormat(currency) {
  const s = '[$' + currencySymbol(currencyOf(currency)) + '-en-US]';
  return '_(' + s + '* #,##0.00_);_(' + s + '* (#,##0.00);_(' + s + '* "-"??_);_(@_)';
}

function formatOf(blockKey, rowKey, colKey, currency) {
  const inBlock = (rows) => Object.keys(rows || {}).some((k) => (blockKey === k || blockKey.endsWith('_' + k)) && rows[k].includes(rowKey));
  const rule = NUMBER_FORMATS.find((r) => (r.columns || []).includes(colKey) || inBlock(r.rows));
  return rule ? rule.format : currencyFormat(currency);
}

// The styling for one page's cells: [{sheet, address, role?, format?, rows?, cols?}] for applyStyles.
// A repeating block's holder rows are one range per column; a client's own cell is never styled.
function styles(binding, pages, pageNumber) {
  const page = pages[pageNumber - 1];
  const currency = pages[0].currency;
  const out = [];
  if (pageNumber === 1) {
    for (const h of binding.headers) {
      out.push({ sheet: h.sheet, address: 'A1', role: 'report_title' }, { sheet: h.sheet, address: 'A2', role: 'report_line' });
    }
  }
  for (const block of page.blocks || []) {
    const b = binding.blocks[block.key];
    if (b.skipped) continue;
    const span = (row) => a1(row, 0) + ':' + a1(row, block.columns.length - 1);
    if (b.title !== null) out.push({ sheet: b.sheet, address: span(b.title), role: 'block_title' });
    if (b.heading !== null) out.push({ sheet: b.sheet, address: span(b.heading), role: 'heading' });
  }
  const runs = {};
  eachCell(pages, page, (block, row, colKey) => {
    const b = binding.blocks[block.key];
    if (b.skipped || binding.cells[keyOf(block.key, row.key, colKey)]) return;
    const format = formatOf(block.key, row.key, colKey, currency);
    const at = b.rows[row.key];
    const col = b.cols[colKey];
    if (row.set === undefined) {
      out.push({ sheet: b.sheet, address: a1(at, col), role: row.key === 'total' ? 'total' : 'data', format, rows: 1, cols: 1 });
      return;
    }
    const run = runs[block.key + '.' + colKey];
    if (run && run.last === at - 1) { run.last = at; return; }
    runs[block.key + '.' + colKey] = { sheet: b.sheet, col, first: at, last: at, role: 'data', format };
    out.push(runs[block.key + '.' + colKey]);
  });
  return out.map((s) => (s.first === undefined ? s : {
    sheet: s.sheet, address: a1(s.first, s.col) + (s.last > s.first ? ':' + a1(s.last, s.col) : ''),
    role: s.role, format: s.format, rows: s.last - s.first + 1, cols: 1 }));
}

// Column widths for applyStyles, in points: A-C 33 characters, the rest 27.
function widths(binding) {
  const points = (chars) => Math.round((chars * 7 + 5) * 0.75);
  const out = [];
  for (const sheet of binding.sheets) {
    const counts = Object.values(binding.blocks).filter((b) => !b.skipped && b.sheet === sheet).map((b) => Object.keys(b.cols).length);
    const n = counts.length ? Math.max(...counts) : 0;
    for (let c = 0; c < n; c++) out.push({ sheet, column: colName(c), width: points(c < 3 ? 33 : 27) });
  }
  return out;
}

const ROLES = {
  report_title: { size: 18, fill: true },
  report_line: { size: 12, fill: true },
  block_title: { size: 12, bold: false, fill: true, height: 60 },
  heading: { size: 12, bold: true, fill: true, border: true, align: true },
  total: { size: 10, bold: true, fill: true },
  data: { size: 10, bold: false },
};

// Applies styles(...) and widths(...) entries; worksheetByName(name) returns an Excel.Worksheet.
function applyStyles(worksheetByName, list) {
  for (const s of list) {
    const ws = worksheetByName(s.sheet);
    if (s.width !== undefined) {
      ws.getRange(s.column + ':' + s.column).format.columnWidth = s.width;
      continue;
    }
    const range = ws.getRange(s.address);
    const role = ROLES[s.role];
    if (role) {
      const f = range.format;
      f.font.name = FONT;
      f.font.size = role.size;
      if (role.bold !== undefined) f.font.bold = role.bold;
      if (role.fill) f.fill.color = FILL;
      if (role.border) {
        const edge = f.borders.getItem('EdgeBottom');
        edge.style = 'Continuous';
        edge.weight = 'Medium';
      }
      if (role.align) {
        f.horizontalAlignment = 'Right';
        range.getCell(0, 0).format.horizontalAlignment = 'Left';
      }
      if (role.height) f.rowHeight = role.height;
    }
    if (s.format !== undefined) range.numberFormat = Array.from({ length: s.rows }, () => new Array(s.cols).fill(s.format));
  }
}

// The range a sheet's blocks fill, from A1 to their last row and column.
function extentOf(binding, sheet) {
  let row = binding.headers.some((h) => h.sheet === sheet) ? 1 : 0;
  let col = 0;
  for (const b of Object.values(binding.blocks)) {
    if (b.skipped || b.sheet !== sheet) continue;
    row = Math.max(row, ...[b.title, b.heading, ...Object.values(b.rows)].filter((r) => r !== null));
    col = Math.max(col, ...Object.values(b.cols));
  }
  return 'A1:' + a1(row, col);
}

// A free name for a refused sheet: its spec name, cut so the name fits, plus ` (Carta)`, then ` (Carta 2)`
// and so on; a name is free when no sheet has it, or when its sheet carries Carta's mark.
function freeName(spec, taken, owned) {
  for (let n = 1; ; n++) {
    const suffix = n === 1 ? ' (Carta)' : ' (Carta ' + n + ')';
    const name = spec.slice(0, SHEET_NAME_MAX - suffix.length) + suffix;
    if (!taken.has(name) || owned(name)) return name;
  }
}

// A sheet-qualified address split at its sheet: "'O''Brien'!A1:B2" → {sheet: "O'Brien", cells: 'A1:B2'};
// sheet is null when the address names none.
function partsOf(address) {
  const m = /^(?:'((?:[^']|'')+)'|([^'!]+))!(.*)$/.exec(address);
  if (!m) return { sheet: null, cells: address };
  return { sheet: m[1] !== undefined ? m[1].replace(/''/g, "'") : m[2], cells: m[3] };
}

// Where a workbook name points: its sheet and cells, and whether Excel has marked it #REF! (its rows or sheet deleted).
function markOf(name) {
  const address = String(name.formula).replace(/^=/, '');
  return { ...partsOf(address), dead: address.includes('#REF!') };
}

// Writes one page and returns {refused, written}; the last page then opens the binding's first sheet, when it can.
// Page 1 first refuses, writing nothing, when a sheet of the binding is neither empty nor Carta's: `refused` maps
// each such sheet's spec name to a free name for it (`layout`'s `sheets`). Otherwise, on each of Carta's own sheets,
// it clears the range of every live Carta mark on that sheet and the extent it writes, adds the missing sheets,
// deletes those marks and every dead (#REF!) Carta mark, and adds one mark per sheet over what it writes there.
// Nothing else on a sheet is cleared.
async function writePage(context, binding, pages, pageNumber) {
  const book = context.workbook;
  if (pageNumber === 1) {
    const sheets = binding.sheets.map((name) => ({
      name, ws: book.worksheets.getItemOrNullObject(name), mark: book.names.getItemOrNullObject(tabKey(name)) }));
    sheets.forEach((s) => { s.ws.load('isNullObject'); s.mark.load('isNullObject'); });
    await context.sync();
    const existing = sheets.filter((s) => !s.ws.isNullObject);
    for (const s of existing) {
      s.used = s.ws.getUsedRangeOrNullObject(true);
      s.used.load('isNullObject');
      s.source = s.ws.getRange('B3');
      s.source.load('values');
      if (!s.mark.isNullObject) {
        s.marked = s.mark.getRangeOrNullObject();
        s.marked.load('isNullObject, address');
      }
    }
    await context.sync();
    const owned = (s) => (s.marked && !s.marked.isNullObject && partsOf(s.marked.address).sheet === s.name)
      || (s.name === 'Cap Table' && s.source.values[0][0] === SOURCE_LINE);
    const refusedSheets = existing.filter((s) => !s.used.isNullObject && !owned(s));
    if (refusedSheets.length) {
      book.worksheets.load('items/name');
      book.names.load('items/name, items/formula');
      await context.sync();
      const taken = new Set(book.worksheets.items.map((w) => w.name).concat(binding.sheets));
      const marked = (name) => book.names.items.some((n) => n.name === tabKey(name)
        && !markOf(n).dead && markOf(n).sheet === name);
      const refused = {};
      for (const s of refusedSheets) {
        const name = freeName(binding.specs[s.name], taken, marked);
        refused[binding.specs[s.name]] = name;
        taken.add(name);
      }
      return { refused, written: 0 };
    }
    book.names.load('items/name, items/formula');
    await context.sync();
    const mine = existing.filter(owned);
    const sheetOf = (n) => mine.find((s) => n.name.startsWith('CartaTab__') && markOf(n).sheet === s.name);
    const marks = book.names.items.filter((n) => sheetOf(n));
    // A dead mark has no range to clear; it is deleted with the rest.
    for (const n of marks) if (!markOf(n).dead) sheetOf(n).ws.getRange(markOf(n).cells).clear('All');
    for (const s of mine) s.ws.getRange(extentOf(binding, s.name)).clear('All');
    for (const s of sheets) if (s.ws.isNullObject) book.worksheets.add(s.name);
    await context.sync();
    // A mark is a convenience: a failed delete or add never stops the write.
    try {
      const broken = (n) => n.name.startsWith('CartaTab__') && markOf(n).dead;
      book.names.items.filter((n) => marks.some((m) => m.name === n.name) || broken(n)).forEach((n) => n.delete());
      await context.sync();
    } catch (e) {
      // Stale marks stay; the write goes on.
    }
    for (const s of sheets) {
      try {
        book.names.add(tabKey(s.name), book.worksheets.getItem(s.name).getRange(extentOf(binding, s.name)));
        await context.sync();
      } catch (e) {
        // The sheet goes unmarked; the write goes on.
      }
    }
  }
  const byName = {};
  const ws = (name) => (byName[name] = byName[name] || book.worksheets.getItem(name));
  const writes = cellsToWrite(binding, pages, pageNumber);
  for (const w of writes) ws(w.sheet).getRange(w.address).formulas = w.formulas;
  applyStyles(ws, styles(binding, pages, pageNumber));
  if (pageNumber === 1) applyStyles(ws, widths(binding));
  await context.sync();
  if (pageNumber === pages.length) {
    try {
      ws(binding.sheets[0]).activate();
      await context.sync();
    } catch (e) {
      // Opening the sheet is a convenience: the write is done either way.
    }
  }
  return { refused: {}, written: writes.length };
}

// Loads the workbook's value at every checked cell and returns compare(...).
async function verify(context, binding, pages) {
  const list = checks(binding, pages);
  const ranges = list.map((c) => context.workbook.worksheets.getItem(c.sheet).getRange(c.address).load('values'));
  await context.sync();
  return compare(list, ranges.map((r) => r.values[0][0]));
}

function shown(value, name, currency) {
  if (typeof value !== 'number') return value === undefined || value === null || value === '' ? '—' : String(value);
  const [, blockKey, rowKey, colKey] = NAME.exec(name);
  const format = formatOf(blockKey, rowKey, colKey, currency);
  const fixed = (style, extra) => new Intl.NumberFormat('en', { style, minimumFractionDigits: 2, maximumFractionDigits: 2, ...extra });
  if (format === '0.00%') return fixed('percent').format(value);
  if (format === 'General' || format === 'yyyy-mm-dd') return String(value);
  if (format === '#,##0.00') return fixed('decimal').format(value);
  return fixed('currency', { currency: currencyOf(currency) }).format(value);
}

// The comparison as markdown: the table (over 25 checks, the mismatches and each block's total row),
// the count line and the Key tie-outs line, amounts in `currency`.
function report(result, currency) {
  const cell = (text) => String(text).replace(/\|/g, '\\|');
  const rows = result.checked > 25
    ? result.rows.filter((r) => r.status === 'Mismatch' || NAME.exec(r.name)[2] === 'total') : result.rows;
  const named = (r) => (r.heading ? r.label + ' — ' + r.heading : r.label);
  const mismatched = result.checked - result.matched;
  const tieOuts = mismatched === 0 ? 'every figure ties out.'
    : result.mismatches.map(named).join('; ') + (mismatched === 1 ? " doesn't tie out." : " don't tie out.");
  return ['| Row | Heading | Carta | Workbook | Status |', '|---|---|---|---|---|']
    .concat(rows.map((r) => '| ' + [r.label, r.heading, shown(r.check, r.name, currency), shown(r.actual, r.name, currency), r.status]
      .map(cell).join(' | ') + ' |'))
    .concat(['', '**' + result.checked + '** items checked. **' + result.matched + '** matched, **' + mismatched + '** mismatched.',
      '', '**Key tie-outs:** ' + tieOuts])
    .join('\n');
}

